"""Write inc/key-plan-land.php: the land drawn on the footer's key plan (AMM-188).

Usage, from the repo root:
    python tools/make-key-plan.py path/to/ne_50m_admin_0_countries.geojson

The data is Natural Earth's 1:50m "Admin 0 - Countries" (public domain, naturalearthdata.com),
from https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/
ne_50m_admin_0_countries.geojson (3.1 MB; fetched 2026-10-08). It is read once here and never
committed: only the outlines this script writes go into the theme.

Each country's outer rings are projected with the theme's plan projection (the same formula as
demas_theme_branch_plan_point() in inc/branches.php, so the branch dots sit where they belong),
clipped to a little outside the frame below, and simplified (Douglas-Peucker, 0.45 plan units,
about a third of a pixel on the footer). Saudi Arabia becomes one path, every other country in
the frame another. Python 3, standard library only.
"""
import json
import math
import os
import sys

# The frame: the whole Kingdom with a little sea and neighbour round it.
LON0, LON1, LAT0, LAT1 = 34.2, 56.0, 15.9, 32.6
K = 20 * math.cos(math.radians(24))
OUT = os.path.join(os.path.dirname(__file__), '..', 'inc', 'key-plan-land.php')


def px(lon):
    return (lon - 36) * K


def py(lat):
    return (32 - lat) * 20


def clip(ring, xmin, ymin, xmax, ymax):
    """Sutherland-Hodgman against a rectangle."""
    def edge(pts, inside, cut):
        out = []
        for i, p in enumerate(pts):
            q = pts[i - 1]
            if inside(p):
                if not inside(q):
                    out.append(cut(q, p))
                out.append(p)
            elif inside(q):
                out.append(cut(q, p))
        return out

    def at_x(x):
        return lambda a, b: (x, a[1] + (b[1] - a[1]) * (x - a[0]) / (b[0] - a[0]))

    def at_y(y):
        return lambda a, b: (a[0] + (b[0] - a[0]) * (y - a[1]) / (b[1] - a[1]), y)

    for inside, cut in ((lambda p: p[0] >= xmin, at_x(xmin)), (lambda p: p[0] <= xmax, at_x(xmax)),
                        (lambda p: p[1] >= ymin, at_y(ymin)), (lambda p: p[1] <= ymax, at_y(ymax))):
        ring = edge(ring, inside, cut)
        if not ring:
            break
    return ring


def simplify(pts, tol):
    """Douglas-Peucker on a closed ring, split at the point farthest from the first."""
    if len(pts) < 4:
        return pts

    def dp(a, b):
        (x1, y1), (x2, y2) = pts[a], pts[b]
        dx, dy = x2 - x1, y2 - y1
        n = math.hypot(dx, dy) or 1e-9
        best, idx = 0, None
        for i in range(a + 1, b):
            x, y = pts[i]
            d = abs(dy * x - dx * y + x2 * y1 - y2 * x1) / n
            if d > best:
                best, idx = d, i
        if best > tol and idx is not None:
            return dp(a, idx)[:-1] + dp(idx, b)
        return [pts[a], pts[b]]

    far = max(range(len(pts)), key=lambda i: (pts[i][0] - pts[0][0]) ** 2 + (pts[i][1] - pts[0][1]) ** 2)
    return dp(0, far)[:-1] + dp(far, len(pts) - 1)


def ring_d(ring):
    return 'M' + 'L'.join(f'{x:.1f} {y:.1f}' for x, y in ring) + 'Z'


x0, x1, y0, y1 = px(LON0), px(LON1), py(LAT1), py(LAT0)
pad = 4
data = json.load(open(sys.argv[1], encoding='utf-8'))
kingdom, neighbours = '', ''
for feature in data['features']:
    geometry = feature['geometry']
    polygons = geometry['coordinates'] if geometry['type'] == 'MultiPolygon' else [geometry['coordinates']]
    for polygon in polygons:
        pts = [(px(lon), py(lat)) for lon, lat in polygon[0]]
        xs, ys = [p[0] for p in pts], [p[1] for p in pts]
        if max(xs) < x0 - pad or min(xs) > x1 + pad or max(ys) < y0 - pad or min(ys) > y1 + pad:
            continue
        pts = simplify(clip(pts, x0 - pad, y0 - pad, x1 + pad, y1 + pad), 0.45)
        if len(pts) < 3:
            continue
        if feature['properties']['ADM0_A3'] == 'SAU':
            kingdom += ring_d(pts)
        else:
            neighbours += ring_d(pts)

assert kingdom and neighbours

php = f"""<?php
/**
 * The land on the footer's key plan (AMM-188): the Kingdom and its
 * neighbours, as SVG path data in the plan's own units (the projection of
 * demas_theme_branch_plan_point()). GENERATED by tools/make-key-plan.py from
 * Natural Earth's 1:50m countries (public domain): run it again to change the
 * frame or the detail, never edit this file by hand.
 *
 * Read by src/branch-plan/render.php, which draws the frame given here.
 *
 * @package Demas_Theme
 */

if ( ! defined( 'ABSPATH' ) ) {{
	exit;
}}

/**
 * The key plan's land and frame.
 *
 * @return array{{frame: array{{0: float, 1: float, 2: float, 3: float}}, kingdom: string, neighbours: string}}
 *         The frame as west, east, south and north (degrees), and two paths.
 */
function demas_theme_get_key_plan_land() {{
	return array(
		'frame'      => array( {LON0}, {LON1}, {LAT0}, {LAT1} ),
		'kingdom'    => '{kingdom}',
		'neighbours' => '{neighbours}',
	);
}}
"""
with open(OUT, 'w', encoding='utf-8', newline='\n') as fh:
    fh.write(php)
print('wrote', os.path.normpath(OUT), len(kingdom), 'and', len(neighbours), 'bytes of path')
